"""M51.S01.T001/T002 safe visual layout for the CMS: nested section/row/column/grid, per-breakpoint style from an
allow-list, per-breakpoint visibility, approved brand tokens, and the shared component/theme/template library.

Safety model (nothing here accepts or produces raw HTML, CSS or script):
- A block's `style` is {breakpoint: {property: value}}. Properties, breakpoints and values come from STYLE_SPEC only;
  anything else is rejected (CmsError), never silently kept. Colours are token NAMES (brand, text, ...), never hex.
- The server turns validated style into a `css` object per breakpoint using fixed lookup tables, so every CSS value is
  generated by this module (never copied from input). The browser applies it as React inline style (escaped).
- Component overrides can only change a short list of typed fields of a block, validated like any other block field.
"""
from __future__ import annotations

import copy
import re
from typing import Any, Optional

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.models.m51_cms_layout import CmsComponent, CmsComponentVersion, CmsSiteLayout

BREAKPOINTS = ("desktop", "tablet", "mobile")          # desktop is the base; tablet and mobile override it (desktop-first)
CONTAINERS = ("section", "row", "column", "grid")
MAX_DEPTH, MAX_CHILDREN, MAX_NODES = 6, 40, 400
KINDS = ("HEADER", "FOOTER", "NAV", "SECTION", "COMPONENT", "THEME", "PAGE_TEMPLATE")
SECTION_TAGS = ("div", "section", "aside", "article")
HEX = re.compile(r"^#[0-9A-Fa-f]{6}$")
SLUG = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")

SPACE = {"none": 0, "xs": 4, "sm": 8, "md": 16, "lg": 24, "xl": 40, "2xl": 64}
COLOR_TOKENS = ("brand", "text", "background", "accent", "muted", "surface", "onbrand")
FONT_STACKS = {"sans": "Inter, Arial, sans-serif", "serif": "Georgia, Times New Roman, serif",
               "mono": "Consolas, Courier New, monospace", "rounded": "Trebuchet MS, Verdana, sans-serif"}
FONT_SIZE = {"xs": "12px", "sm": "14px", "base": "16px", "lg": "18px", "xl": "22px", "2xl": "28px", "3xl": "36px", "4xl": "48px"}
FONT_WEIGHT = {"normal": 400, "medium": 500, "semibold": 600, "bold": 700}
LINE_HEIGHT = {"tight": 1.2, "normal": 1.5, "relaxed": 1.8}
WIDTH = {"auto": None, "narrow": 560, "content": 768, "wide": 1100, "full": None}
RADIUS = {"none": 0, "sm": 4, "md": 8, "lg": 16, "full": 9999}
BORDER = {"none": 0, "thin": 1, "medium": 3}
SHADOW = {"none": "none", "sm": "0 1px 3px rgba(0,0,0,0.15)", "md": "0 4px 12px rgba(0,0,0,0.18)"}
ALIGN = {"left": "left", "center": "center", "right": "right"}
JUSTIFY = {"start": "flex-start", "center": "center", "end": "flex-end", "between": "space-between"}
VALIGN = {"start": "start", "center": "center", "end": "end", "stretch": "stretch"}

# property -> allowed values (the single source for validation, the editor's controls and css generation)
STYLE_SPEC: dict[str, tuple] = {
    **{p: tuple(SPACE) for p in ("padding_top", "padding_bottom", "padding_left", "padding_right", "margin_top", "margin_bottom")},
    "align": tuple(ALIGN), "width": tuple(WIDTH),
    "font_size": tuple(FONT_SIZE), "font_weight": tuple(FONT_WEIGHT), "font_family": ("body", "heading"), "line_height": tuple(LINE_HEIGHT),
    "color": COLOR_TOKENS, "background": COLOR_TOKENS + ("none",), "border_color": COLOR_TOKENS,
    "border": tuple(BORDER), "radius": tuple(RADIUS), "shadow": tuple(SHADOW),
    "gap": tuple(SPACE), "justify": tuple(JUSTIFY), "valign": tuple(VALIGN),
    "span": tuple(range(1, 13)), "cols": tuple(range(1, 7)),
}
TYPE_ONLY = {"gap": ("row", "grid"), "justify": ("row", "grid"), "valign": ("row", "grid"), "span": ("column",), "cols": ("grid",)}

# fields a page may override on a block of a reused component (value kinds are checked by the caller's validators)
OVERRIDABLE = ("text", "title", "subtitle", "label", "href", "alt", "name", "size", "price", "style", "hide")


def _err(msg: str):
    from app.services.cms_service import CmsError
    return CmsError(msg)


def clean_style(style: Any, btype: str) -> dict:
    """Validate {breakpoint: {property: value}}; unknown breakpoints, properties and values are errors."""
    if style in (None, {}):
        return {}
    if not isinstance(style, dict):
        raise _err("style must be an object of breakpoints")
    out: dict = {}
    for bp, props in style.items():
        if bp not in BREAKPOINTS:
            raise _err(f"Unknown breakpoint {str(bp)[:20]!r}; use {', '.join(BREAKPOINTS)}")
        if not isinstance(props, dict):
            raise _err(f"style.{bp} must be an object")
        clean: dict = {}
        for k, v in props.items():
            if k not in STYLE_SPEC:
                raise _err(f"Unknown style property {str(k)[:30]!r}")
            if k in TYPE_ONLY and btype != "any" and btype not in TYPE_ONLY[k]:
                raise _err(f"Style property {k} applies to {', '.join(TYPE_ONLY[k])} only")
            if k in ("span", "cols"):
                try:
                    v = int(v) if isinstance(v, (int, str)) and not isinstance(v, bool) else None
                except ValueError:
                    v = None
            if v not in STYLE_SPEC[k] or isinstance(v, bool):
                raise _err(f"Value {str(v)[:30]!r} is not allowed for {k}")
            clean[k] = v
        if clean:
            out[bp] = clean
    return out


def clean_hide(hide: Any) -> list:
    if not hide:
        return []
    if not isinstance(hide, list) or any(x not in BREAKPOINTS for x in hide):
        raise _err(f"hide must be a list of {', '.join(BREAKPOINTS)}")
    return [b for b in BREAKPOINTS if b in hide]


def clean_overrides(ov: Any) -> dict:
    """{block id: {field: value}} restricted to OVERRIDABLE fields; strings go through the same checks as block fields."""
    from app.services.cms_service import _text, href
    if not ov:
        return {}
    if not isinstance(ov, dict) or len(ov) > 40:
        raise _err("overrides must be an object of at most 40 block ids")
    out: dict = {}
    for bid, fields in ov.items():
        bid = re.sub(r"[^\w-]", "", str(bid))[:20]
        if not isinstance(fields, dict):
            raise _err("An override must be an object")
        o: dict = {}
        for k, v in fields.items():
            if k not in OVERRIDABLE:
                raise _err(f"Field {str(k)[:30]!r} cannot be overridden")
            if k == "style":
                o[k] = clean_style(v, "any")      # type-only props are rechecked when the override is applied to a block
            elif k == "hide":
                o[k] = clean_hide(v)
            elif k == "href":
                o[k] = href(v)
            else:
                o[k] = _text(v, 8000 if k == "text" else 400)
        out[bid] = o
    return out


def nodes_ok(blocks: Any) -> None:
    """Refuse an oversized or too deep document before walking it recursively."""
    stack, n = [(blocks, 0)], 0
    while stack:
        cur, d = stack.pop()
        if d > MAX_DEPTH + 2:
            raise _err(f"Layouts nest at most {MAX_DEPTH} levels")
        for b in cur if isinstance(cur, list) else []:
            if not isinstance(b, dict):
                continue
            n += 1
            if n > MAX_NODES:
                raise _err(f"A document holds at most {MAX_NODES} blocks including nested ones")
            for k in ("children", "left", "right"):
                if isinstance(b.get(k), list):
                    stack.append((b[k], d + 1))


# ── css generation (values come from the tables above only) ─────────────────────

def css_for(style: dict, btype: str, tokens: dict) -> dict:
    """{breakpoint: {reactProp: value}} cascading desktop → tablet → mobile."""
    colors = tokens["colors"]
    out: dict = {}
    acc: dict = {}
    for bp in BREAKPOINTS:
        acc = {**acc, **(style.get(bp) or {})}
        if bp == "mobile":
            if btype == "column" and "span" not in (style.get("mobile") or {}):
                acc = {**acc, "span": 12}          # columns stack on phones unless the author chose otherwise
            if btype == "grid" and "cols" not in (style.get("mobile") or {}):
                acc = {**acc, "cols": 1}
        out[bp] = _css(acc, btype, colors, tokens)
    return out


def _css(s: dict, btype: str, colors: dict, tokens: dict) -> dict:
    c: dict = {}
    for side, prop in (("top", "paddingTop"), ("bottom", "paddingBottom"), ("left", "paddingLeft"), ("right", "paddingRight")):
        if f"padding_{side}" in s:
            c[prop] = SPACE[s[f"padding_{side}"]]
    for side, prop in (("top", "marginTop"), ("bottom", "marginBottom")):
        if f"margin_{side}" in s:
            c[prop] = SPACE[s[f"margin_{side}"]]
    if "align" in s:
        c["textAlign"] = ALIGN[s["align"]]
    if "width" in s:
        c["maxWidth"] = WIDTH[s["width"]] or "none"
        c["marginLeft"] = c["marginRight"] = "auto"
    if "font_size" in s:
        c["fontSize"] = FONT_SIZE[s["font_size"]]
    if "font_weight" in s:
        c["fontWeight"] = FONT_WEIGHT[s["font_weight"]]
    if "font_family" in s:
        c["fontFamily"] = FONT_STACKS[tokens["body_font"] if s["font_family"] == "body" else tokens["heading_font"]]
    if "line_height" in s:
        c["lineHeight"] = LINE_HEIGHT[s["line_height"]]
    if "color" in s:
        c["color"] = colors[s["color"]]
    if "background" in s:
        c["backgroundColor"] = "transparent" if s["background"] == "none" else colors[s["background"]]
    if "border" in s:
        c["borderStyle"] = "none" if s["border"] == "none" else "solid"
        c["borderWidth"] = BORDER[s["border"]]
        c["borderColor"] = colors[s.get("border_color", "muted")]
    elif "border_color" in s:
        c["borderColor"] = colors[s["border_color"]]
    if "radius" in s:
        c["borderRadius"] = RADIUS[s["radius"]]
    if "shadow" in s:
        c["boxShadow"] = SHADOW[s["shadow"]]
    if btype in ("row", "grid"):
        c["display"] = "grid"
        c["gridTemplateColumns"] = f"repeat({s.get('cols', 12) if btype == 'grid' else 12}, minmax(0, 1fr))"
        if "gap" in s:
            c["gap"] = SPACE[s["gap"]]
        if "valign" in s:
            c["alignItems"] = VALIGN[s["valign"]]
        if "justify" in s:
            c["justifyContent"] = JUSTIFY[s["justify"]]
    if btype == "column":
        c["gridColumn"] = f"span {s.get('span', 12)} / span {s.get('span', 12)}"
        c["minWidth"] = 0
    return c


def attach_css(blocks: list, tokens: dict) -> list:
    """Add `css` (per breakpoint) to every block that has style or is a layout container; recurses everywhere."""
    out = []
    for b in blocks:
        b = dict(b)
        if b.get("style") or b["type"] in CONTAINERS:
            b["css"] = css_for(b.get("style") or {}, b["type"], tokens)
        for k in ("children", "left", "right", "blocks"):
            if isinstance(b.get(k), list):
                b[k] = attach_css(b[k], tokens)
        out.append(b)
    return out


# ── brand tokens ───────────────────────────────────────────────────────────────

DEFAULT_TOKENS = {"colors": {"brand": "#1D4ED8", "text": "#111827", "background": "#FFFFFF", "accent": "#F59E0B", "muted": "#6B7280",
                             "surface": "#F3F4F6", "onbrand": "#FFFFFF"},
                  "body_font": "sans", "heading_font": "sans", "radius": 8}


def validate_tokens(t: Any) -> tuple[dict, list[str]]:
    """Approved brand tokens: 7 named colours (#RRGGBB), two font stacks from the allow-list, a corner radius."""
    t = t or {}
    if not isinstance(t, dict):
        raise _err("tokens must be an object")
    extra = set(t) - {"colors", "body_font", "heading_font", "radius", "logo_asset_ref"}
    if extra:
        raise _err(f"Unknown token {sorted(map(str, extra))[0][:30]!r}")
    cols = t.get("colors") or {}
    if not isinstance(cols, dict) or set(cols) - set(COLOR_TOKENS):
        raise _err(f"Colour tokens are {', '.join(COLOR_TOKENS)}")
    colors = {**DEFAULT_TOKENS["colors"], **cols}
    for k, v in colors.items():
        if not isinstance(v, str) or not HEX.match(v):
            raise _err(f"{k} must be a #RRGGBB colour")
        colors[k] = v.upper()
    out = {"colors": colors, "radius": 8}
    for k in ("body_font", "heading_font"):
        v = t.get(k, "sans")
        if v not in FONT_STACKS:
            raise _err(f"{k} must be one of {', '.join(FONT_STACKS)}")
        out[k] = v
    try:
        r = int(t.get("radius", 8))
    except (TypeError, ValueError):
        raise _err("radius must be a number from 0 to 24")
    if not 0 <= r <= 24:
        raise _err("radius must be a number from 0 to 24")
    out["radius"] = r
    if t.get("logo_asset_ref"):
        out["logo_asset_ref"] = str(t["logo_asset_ref"])[:60]
    from app.services.email_design_service import contrast
    warn = []
    if contrast(colors["text"], colors["background"]) < 4.5:
        warn.append("Text colour on the background is below WCAG AA contrast (4.5:1).")
    if contrast(colors["onbrand"], colors["brand"]) < 4.5:
        warn.append("Text on the brand colour is below WCAG AA contrast (4.5:1).")
    return out, warn


def tokens_from_site_theme(theme: dict) -> dict:
    """The M46 site theme as tokens (used until a THEME component is assigned)."""
    t = copy.deepcopy(DEFAULT_TOKENS)
    m = {"brand": "brand_color", "text": "text_color", "background": "background", "accent": "accent"}
    for k, src in m.items():
        if HEX.match(str((theme or {}).get(src) or "")):
            t["colors"][k] = theme[src].upper()
    font = (theme or {}).get("font")
    t["body_font"] = t["heading_font"] = next((k for k, v in FONT_STACKS.items() if v == font), "sans")
    try:
        t["radius"] = max(0, min(24, int((theme or {}).get("radius", 8))))
    except (TypeError, ValueError):
        pass
    return t


def theme_from_tokens(tokens: dict) -> dict:
    c = tokens["colors"]
    return {"brand_color": c["brand"], "text_color": c["text"], "background": c["background"], "accent": c["accent"],
            "font": FONT_STACKS[tokens["body_font"]], "radius": str(tokens["radius"])}


def email_theme(tokens: dict) -> dict:
    """Read-only mapping of site tokens to the e-mail designer's theme keys (the designer's own store is not touched)."""
    c = tokens["colors"]
    return {"brand_color": c["brand"], "text_color": c["text"], "background": c["surface"], "font": "Arial, Helvetica, sans-serif"}


# ── library: validation, lookup, resolution ───────────────────────────────────

def _no_component_refs(blocks: Any) -> None:
    stack = [blocks]
    while stack:
        cur = stack.pop()
        for b in cur if isinstance(cur, list) else []:
            if isinstance(b, dict):
                if b.get("type") == "component":
                    raise _err("A library item cannot contain another component reference")
                for k in ("children", "left", "right"):
                    stack.append(b.get(k))


def validate_component(kind: str, draft: Any) -> tuple[dict, list[str]]:
    """Content of one library item. blocks (+ optional per-locale variants) for layout kinds, tokens for a THEME."""
    from app.services import cms_service as cms
    if kind not in KINDS:
        raise _err(f"Kind must be one of {', '.join(KINDS)}")
    if not isinstance(draft, dict):
        raise _err("A library item must be an object")
    if kind == "THEME":
        tok, warn = validate_tokens(draft.get("tokens"))
        return {"tokens": tok}, warn
    if kind == "PAGE_TEMPLATE":
        _no_component_refs(draft.get("blocks"))
        doc, warn = cms.validate_doc(draft)
        return doc, warn
    _no_component_refs(draft.get("blocks"))
    warn: list[str] = []
    main, w = cms.validate_doc({"blocks": draft.get("blocks")})
    warn += w
    out: dict = {"blocks": main["blocks"]}
    locs = draft.get("locales") or {}
    if not isinstance(locs, dict):
        raise _err("locales must be an object")
    out["locales"] = {}
    for loc, blocks in locs.items():
        if loc not in cms.LOCALES:
            raise _err(f"Unknown locale {str(loc)[:10]!r}")
        _no_component_refs(blocks)
        d, w = cms.validate_doc({"blocks": blocks})
        out["locales"][loc] = d["blocks"]
        warn += w
    return out, warn


def blocks_for(content: dict, locale: Optional[str]) -> list:
    return list((content.get("locales") or {}).get(locale or "") or content.get("blocks") or [])


async def live_component(db: AsyncSession, site_id, key: str, kinds: Optional[tuple] = None) -> Optional[tuple[CmsComponent, CmsComponentVersion]]:
    c = (await db.execute(select(CmsComponent).where(CmsComponent.site_id == site_id, CmsComponent.key == key))).scalar_one_or_none()
    if c is None or not c.live_version_id or (kinds and c.kind not in kinds):
        return None
    v = await db.get(CmsComponentVersion, c.live_version_id)
    return (c, v) if v else None


def apply_overrides(blocks: list, ov: dict) -> list:
    """Per-page override of a reused component: only OVERRIDABLE fields of blocks addressed by id, re-validated."""
    from app.services.cms_service import CmsError
    out = []
    for b in blocks:
        b = dict(b)
        o = ov.get(b.get("id"))
        if o:
            for k, v in o.items():
                if k == "style":
                    try:
                        v = clean_style(v, b["type"])
                    except CmsError:
                        continue
                if k in ("style", "hide") or k in b:       # text-like fields only where the block has them
                    b[k] = v
        for k in ("children", "left", "right"):
            if isinstance(b.get(k), list):
                b[k] = apply_overrides(b[k], ov)
        out.append(b)
    return out


async def site_layout(db: AsyncSession, site_id) -> Optional[CmsSiteLayout]:
    return (await db.execute(select(CmsSiteLayout).where(CmsSiteLayout.site_id == site_id))).scalar_one_or_none()


async def effective_tokens(db: AsyncSession, site) -> dict:
    lay = await site_layout(db, site.id)
    if lay and lay.theme_key:
        hit = await live_component(db, site.id, lay.theme_key, ("THEME",))
        if hit:
            return validate_tokens(hit[1].content.get("tokens"))[0]
    return tokens_from_site_theme(site.theme or {})


async def theme_for(db: AsyncSession, site, tokens: dict) -> dict:
    """The legacy-shaped theme the page shell uses: from the assigned THEME component, else the site's own theme."""
    from app.services.cms_service import validate_theme
    lay = await site_layout(db, site.id)
    return theme_from_tokens(tokens) if lay and lay.theme_key else validate_theme(site.theme or {})


async def public_layout(db: AsyncSession, site, page_layout: Optional[dict], locale: str, tokens: dict) -> dict:
    """Header / nav / footer blocks for a page: the site's assignment unless the page says "none" or names another item."""
    from app.services import cms_service as cms
    lay = await site_layout(db, site.id)
    out: dict = {}
    for slot, kind in (("header", "HEADER"), ("nav", "NAV"), ("footer", "FOOTER")):
        choice = (page_layout or {}).get(slot, "inherit")
        key = getattr(lay, f"{slot}_key", None) if choice == "inherit" and lay else (None if choice in ("inherit", "none") else choice)
        hit = await live_component(db, site.id, key, (kind,)) if key else None
        blocks = blocks_for(hit[1].content, locale) if hit else []
        out[slot] = attach_css(await cms.expand(db, site, blocks, depth=1, locale=locale), tokens) if blocks else []
    out["tokens"] = tokens
    return out


def clean_page_layout(v: Any) -> dict:
    if not v:
        return {}
    if not isinstance(v, dict) or set(v) - {"header", "nav", "footer"}:
        raise _err("layout may set header, nav and footer only")
    out = {}
    for k, x in v.items():
        x = str(x)
        if x not in ("inherit", "none") and not SLUG.match(x):
            raise _err(f"layout.{k} must be inherit, none or a component key")
        out[k] = x
    return out



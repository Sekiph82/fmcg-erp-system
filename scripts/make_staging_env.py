"""Write .env.staging for the local staging rehearsal (docker-compose.staging.yml).

Starts from .env.production.example so the production validators run unchanged, fills every
secret with fresh random local-only values, points URLs at the staging host ports and leaves
live-provider credentials empty (those integrations stay disabled in staging). Secrets are
never printed. Refuses to overwrite an existing file unless --force is given.
"""
import secrets
import string
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = ROOT / ".env.production.example"
TARGET = ROOT / ".env.staging"


def _password(n=24):
    alphabet = string.ascii_letters + string.digits
    core = "".join(secrets.choice(alphabet) for _ in range(n))
    return f"Stg{core}#9a"  # satisfies upper/lower/digit/special policy


def build() -> str:
    db_password = secrets.token_hex(16)
    redis_password = secrets.token_hex(16)
    values = {
        "POSTGRES_USER": "fmcg_staging",
        "POSTGRES_PASSWORD": db_password,
        "POSTGRES_DB": "fmcg_staging",
        "DATABASE_URL": f"postgresql+asyncpg://fmcg_staging:{db_password}@db:5432/fmcg_staging",
        "REDIS_PASSWORD": redis_password,
        "REDIS_URL": f"redis://:{redis_password}@redis:6379/0",
        "SECRET_KEY": secrets.token_urlsafe(48),
        "WEBHOOK_SECRET_ENCRYPTION_KEY": secrets.token_urlsafe(48),
        "BACKEND_CORS_ORIGINS": '["http://localhost:13000"]',
        "NEXT_PUBLIC_API_URL": "http://localhost:18000",
        "INITIAL_ADMIN_EMAIL": "staging-admin@example.invalid",
        "INITIAL_ADMIN_PASSWORD": _password(),
        "SEED_INITIAL_ADMIN": "true",
        "ERP_SEED_MANAGEMENT_USERS": "false",
        "TWO_FACTOR_EMAIL_ENABLED": "false",
        "TWO_FACTOR_SMS_ENABLED": "false",
    }
    for role in ("ADMIN", "CEO", "CTO", "CMO", "COO", "CFO"):  # management seeding is off in staging
        values[f"ERP_{role}_PASSWORD"] = ""
    blank_if_placeholder = True
    out = ["# Generated by scripts/make_staging_env.py - local staging only, never commit."]
    for raw in TEMPLATE.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        if key in values:
            value = values[key]
        elif blank_if_placeholder and any(m in value for m in ("CHANGE_ME", "yourdomain", "example.com")):
            value = ""
        out.append(f"{key}={value}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    if TARGET.exists() and "--force" not in sys.argv:
        sys.exit(f"{TARGET.name} already exists; pass --force to regenerate it.")
    TARGET.write_text(build(), encoding="utf-8")
    print(f"wrote {TARGET.name} (secrets not shown)")
